#!/usr/bin/env python3
# Regenerate test/host/catalog_example_lines.tsv from a droidnet-command-library checkout.
# Part of the DroidNet RSeries fork. Copyright (c) 2026 Travis Cook. LGPL-2.1-only.
#
# Usage:  python3 test/host/refresh_catalog_examples.py <library checkout>
#
# Writes one "<command id>\t<line>" row per "examples" entry of every board the library's
# libraries/manifest.json lists, in manifest order, then component, command and example order.
# Lines starting with "# " are provenance comments (no command id starts with "#").
# The snapshot is checked in so the fork's host suite (prefix_guard.cpp) runs on its own.
# Python 3 standard library only.
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "catalog_example_lines.tsv")


def library_revision(lib):
    try:
        sha = subprocess.run(["git", "-C", lib, "rev-parse", "--short=12", "HEAD"],
                             capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", lib, "status", "--porcelain", "--", "libraries"],
                               capture_output=True, text=True, check=True).stdout.strip()
        return sha + ("-dirty" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown (not a git checkout)"


def main(argv):
    if len(argv) != 2:
        print("usage: refresh_catalog_examples.py <droidnet-command-library checkout>", file=sys.stderr)
        return 2
    lib = os.path.abspath(argv[1])
    manifest_path = os.path.join(lib, "libraries", "manifest.json")
    with open(manifest_path, encoding="utf-8") as f:
        manifest = json.load(f)

    rows = []
    for board in manifest["boards"]:
        with open(os.path.join(lib, "libraries", board["file"]), encoding="utf-8") as f:
            data = json.load(f)
        for component in data.get("components", []):
            for command in component.get("commands", []):
                for line in command.get("examples", []):
                    if not isinstance(line, str) or any(c in line for c in "\t\r\n"):
                        print(f"error: {command['id']} has an example the TSV cannot hold: {line!r}",
                              file=sys.stderr)
                        return 1
                    rows.append((command["id"], line))

    version = manifest["libraryVersion"]
    boards = len(manifest["boards"])
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by test/host/refresh_catalog_examples.py. Do not edit by hand.\n")
        f.write(f"# Source: droidnet-command-library {version} @ {library_revision(lib)}, "
                f"{boards} boards, {len(rows)} example lines.\n")
        f.write("# Format: <command id><TAB><line>, one row per examples entry, in manifest order.\n")
        for command_id, line in rows:
            f.write(f"{command_id}\t{line}\n")
    print(f"wrote {len(rows)} rows from library {version} ({boards} boards) to {os.path.relpath(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
