#!/usr/bin/env python3
"""
Test script to simulate WiFi page generation and validate the complete JavaScript
"""

import re
import subprocess
import tempfile
import os
import sys

def extract_wifi_page_javascript():
    """Extract and simulate the WiFi page JavaScript generation"""
    
    # Read WebPages.h
    webpages_path = os.path.join(os.path.dirname(__file__), '..', 'WebPages.h')
    with open(webpages_path, 'r') as f:
        content = f.read()
    
    # Read WifiWebServer.h for base JavaScript
    wifiserver_path = os.path.join(os.path.dirname(__file__), '..', 'lib', 'Reeltwo', 'src', 'wifi', 'WifiWebServer.h')
    with open(wifiserver_path, 'r') as f:
        wifiserver_content = f.read()
    
    # Extract base JavaScript from WifiWebServer.h
    base_js = []
    
    # Find emitCSS in WifiWebServer which includes some JavaScript
    css_pattern = r'virtual void emitCSS\(Print& out\)\s*{([^}]+(?:{[^}]*}[^}]*)*})}'
    css_match = re.search(css_pattern, wifiserver_content, re.DOTALL)
    if css_match:
        css_body = css_match.group(1)
        # Extract script content from CSS section
        script_matches = re.findall(r'out\.print[ln]*\s*\(\s*"([^"]*<script[^>]*>.*?</script>[^"]*)"\s*\)', css_body, re.DOTALL)
        for script in script_matches:
            script = script.replace('\\"', '"').replace('\\n', '\n')
            # Extract just the JavaScript
            js_match = re.search(r'<script[^>]*>(.*?)</script>', script, re.DOTALL)
            if js_match:
                base_js.append(js_match.group(1))
    
    # Find JavaScript functions generated by widgets
    widget_js = []
    
    # Common widget patterns that generate JavaScript
    update_funcs = re.findall(r'"function\s+(updateValue_\w+)\s*\([^)]*\)\s*{([^}]+)}"', wifiserver_content)
    for func_name, func_body in update_funcs:
        widget_js.append(f"function {func_name}() {{ {func_body} }}")
    
    pressed_funcs = re.findall(r'"function\s+(pressed_\w+)\s*\([^)]*\)\s*{([^}]+)}"', wifiserver_content)
    for func_name, func_body in pressed_funcs:
        widget_js.append(f"function {func_name}() {{ {func_body} }}")
    
    # Extract WiFi page specific JavaScript from WebPages.h
    wifi_js = []
    
    # Find WJavaScript block
    js_pattern = r'WJavaScript\s*\(\s*((?:"[^"]*"\s*)+)\s*\)'
    js_matches = re.findall(js_pattern, content, re.DOTALL)
    
    for match in js_matches:
        # Extract individual strings
        strings = re.findall(r'"([^"]*)"', match)
        js_code = ''.join(strings)
        wifi_js.append(js_code)
    
    # Combine all JavaScript
    full_js = "\n".join(base_js + widget_js + wifi_js)
    
    # Add mock functions for widget-generated functions that we might have missed
    # These would be generated dynamically based on widget IDs
    mock_widget_js = """
// Mock widget functions that would be generated dynamically
function updateValue_newssid(value) {
    fetchNoload('/updateValue_newssid', value);
}
function updateValue_newpass(value) {
    fetchNoload('/updateValue_newpass', value);
}
function pressed_addnet() {
    window.location.href = '/pressed_addnet';
}
"""
    
    full_js = full_js + "\n" + mock_widget_js
    
    return full_js

def validate_javascript(js_code):
    """Validate JavaScript using Node.js"""
    
    # Write to temporary file
    with tempfile.NamedTemporaryFile(mode='w', suffix='.js', delete=False) as f:
        f.write(js_code)
        temp_file = f.name
    
    try:
        # Use node to check syntax
        result = subprocess.run(
            ['node', '--check', temp_file],
            capture_output=True,
            text=True
        )
        
        if result.returncode != 0:
            print("❌ JavaScript validation failed!")
            print(result.stderr)
            
            # Try to find the error line
            lines = js_code.split('\n')
            error_match = re.search(r':(\d+)', result.stderr)
            if error_match:
                line_num = int(error_match.group(1))
                print(f"\nError around line {line_num}:")
                start = max(0, line_num - 5)
                end = min(len(lines), line_num + 5)
                for i in range(start, end):
                    prefix = ">>> " if i == line_num - 1 else "    "
                    print(f"{prefix}{i+1:4d}: {lines[i]}")
        else:
            print("✅ JavaScript validation passed!")
            print(f"   Total lines: {len(js_code.split(chr(10)))}")
            
            # Count functions
            functions = re.findall(r'function\s+(\w+)', js_code)
            print(f"   Functions found: {len(functions)}")
            for func in sorted(set(functions)):
                print(f"     - {func}")
                
    finally:
        os.unlink(temp_file)
    
    return result.returncode == 0

def main():
    print("Extracting WiFi page JavaScript...")
    js_code = extract_wifi_page_javascript()
    
    # Save to file for inspection
    output_file = os.path.join(os.path.dirname(__file__), 'wifi_page_generated.js')
    with open(output_file, 'w') as f:
        f.write(js_code)
    print(f"Saved generated JavaScript to: {output_file}")
    
    print("\nValidating JavaScript...")
    if validate_javascript(js_code):
        sys.exit(0)
    else:
        sys.exit(1)

if __name__ == '__main__':
    main()